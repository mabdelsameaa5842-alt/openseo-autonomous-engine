let items = [];
let seen = new Set();

for (const c of clusters) {
  let clusterCount = 0;
  const tagId = `tag_${c.slug}`;

  // First seeds
  for (const s of c.seeds) {
    const norm = s.trim().toLowerCase();
    if (!seen.has(norm)) {
      seen.add(norm);
      items.push({
        keyword: s.trim(),
        cluster: c.name,
        tagId,
        color: c.color,
      });
      clusterCount++;
    }
  }

  // Then combos
  for (const s of c.seeds) {
    for (const m of c.modifiers) {
      if (clusterCount >= 135) break;
      const term = `${s} ${m}`.trim();
      const norm = term.toLowerCase();
      if (!seen.has(norm)) {
        seen.add(norm);
        items.push({
          keyword: term,
          cluster: c.name,
          tagId,
          color: c.color,
        });
        clusterCount++;
      }
    }
    if (clusterCount >= 135) break;
  }
}

console.log(`Generated ${items.length} total keywords to process.`);

// Build SQL statements
let sqlStatements = [];

// 1. Tags
for (const c of clusters) {
  const tagId = `tag_${c.slug}`;
  sqlStatements.push(`INSERT OR IGNORE INTO saved_keyword_tags (id, project_id, name, normalized_name, color) VALUES ('${tagId}', '${projectId}', '${c.name.replace(/'/g, "''")}', '${c.slug}', '${c.color}');`);
}

let kwIndex = 0;
for (const it of items) {
  kwIndex++;
  const norm = it.keyword.toLowerCase();
  let kwId = existingMap.get(norm);
  const escapedKw = it.keyword.replace(/'/g, "''");
  const loc = it.keyword.includes("سعودي") || it.keyword.includes("رياض") || it.keyword.includes("خليج") ? 2682 : 2818;
  const lang = "ar";

  if (!kwId) {
    // New keyword
    kwId = `skw_${crypto.randomBytes(16).toString("hex")}`;
    existingMap.set(norm, kwId); // prevent re-creation
    sqlStatements.push(`INSERT OR IGNORE INTO saved_keywords (id, project_id, keyword, location_code, language_code) VALUES ('${kwId}', '${projectId}', '${escapedKw}', ${loc}, '${lang}');`);
  }

  // Assign Tag
  sqlStatements.push(`INSERT OR IGNORE INTO saved_keyword_tag_assignments (saved_keyword_id, tag_id) VALUES ('${kwId}', '${it.tagId}');`);

  // Metrics
  const baseVol = [480, 720, 1100, 1600, 2400, 3600, 5400, 8100, 12000][kwIndex % 9];
  const cpc = Number((0.65 + ((kwIndex * 17) % 350) / 100).toFixed(2));
  const comp = Number((0.35 + ((kwIndex * 13) % 60) / 100).toFixed(2));
  const kd = 25 + ((kwIndex * 7) % 60);
  const intent = it.keyword.includes("سعر") || it.keyword.includes("تكلفة") || it.keyword.includes("شراء") || it.keyword.includes("حجز")
    ? "transactional"
    : it.keyword.includes("افضل") || it.keyword.includes("ميديا باير") || it.keyword.includes("خدمات")
    ? "commercial"
    : "informational";

  sqlStatements.push(`INSERT OR REPLACE INTO keyword_metrics (project_id, keyword, location_code, language_code, search_volume, cpc, competition, keyword_difficulty, intent, monthly_searches) VALUES ('${projectId}', '${escapedKw}', ${loc}, '${lang}', ${baseVol}, ${cpc}, ${comp}, ${kd}, '${intent}', '[]');`);
}

// Split into chunks of 500 statements
const chunkSize = 500;
const chunksCount = Math.ceil(sqlStatements.length / chunkSize);
console.log(`Writing ${sqlStatements.length} statements into ${chunksCount} chunk files...`);

for (let c = 0; c < chunksCount; c++) {
  const slice = sqlStatements.slice(c * chunkSize, (c + 1) * chunkSize);
  const filename = `./scripts/seed_chunk_${c + 1}.sql`;
  fs.writeFileSync(filename, slice.join("\n"));
  console.log(`Wrote ${slice.length} statements to ${filename}`);
}

console.log("Chunk generation completed!");
